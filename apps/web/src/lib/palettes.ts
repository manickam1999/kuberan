/**
 * Palette registry: the one list of UI palettes on the web side.
 *
 * - The ids must equal the Go list in apps/api/internal/appearance (a Go test
 *   reads this file and compares them; keep one `id: "..."` line per palette).
 * - The token values are the design prototype's, one set per colour mode. The
 *   CSS in app/globals.css mirrors them (a Vitest test compares the two), the
 *   Settings tiles preview them, and palettes.test.ts holds them to the WCAG
 *   contrast rules.
 *
 * Token names follow the prototype: ink0..ink3 are the surfaces (background,
 * card, elevated, muted), `accent` is the primary colour and `accentInk` the
 * text on it, `pos` / `neg` / `warn` are the money and status colours, and
 * k1..k8 are the categorical chart colours.
 */

export type PaletteId =
  | "gold"
  | "cobalt"
  | "saffron"
  | "graphite"
  | "lagoon"
  | "nord"
  | "catppuccin"
  | "gruvbox";

