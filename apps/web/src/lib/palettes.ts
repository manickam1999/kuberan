const BY_ID = new Map<string, Palette>(PALETTES.map((p) => [p.id, p]));

/** Narrows an arbitrary string to a known palette id. */
export function isPaletteId(value: unknown): value is PaletteId {
  return typeof value === "string" && BY_ID.has(value);
}

/** The palette for an id; falls back to the built-in default. */
export function getPalette(id: string | null | undefined): Palette {
  return (id && BY_ID.get(id)) || (BY_ID.get(BUILT_IN_PALETTE) as Palette);
}
